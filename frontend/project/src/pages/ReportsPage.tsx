// ─── Types ───────────────────────────────────────────────────────────────────

interface PracticeRow {
  is_correct: boolean;
  created_at: string;
  question: { topic: PracticeTopic; difficulty: QuestionDifficulty; question: string } | null;
}

interface MockRow {
  total_questions: number;
  correct_answers: number;
  duration_seconds: number;
  created_at: string;
}

interface PageData {
  practiceRows: PracticeRow[];
  mockRows: MockRow[];
}

type ReportType = 'practice' | 'mock' | 'readiness';

interface ReportCard {
  id: ReportType;
  title: string;
  summary: string;
  icon: React.ElementType;
  iconBg: string;
  iconText: string;
}

// ─── Constants ───────────────────────────────────────────────────────────────

const REPORT_CARDS: ReportCard[] = [
  {
    id: 'practice',
    title: 'Practice Report',
    summary: 'Total attempts, accuracy by topic, and your most missed question types.',
    icon: ClipboardList,
    iconBg: 'bg-primary-50',
    iconText: 'text-primary-600',
  },
  {
    id: 'mock',
    title: 'Mock Test Report',
    summary: 'Tests taken, average score, best and worst result, and your average time per question.',
    icon: ChartBar,
    iconBg: 'bg-accent-50',
    iconText: 'text-accent-600',
  },
  {
    id: 'readiness',
    title: 'Readiness Report',
    summary: 'An overall placement readiness score (0–100) derived from accuracy and consistency.',
    icon: FileText,
    iconBg: 'bg-success-50',
    iconText: 'text-success-600',
  },
];

// ─── Helpers ─────────────────────────────────────────────────────────────────

function pct(c: number, t: number): number | null {
  return t === 0 ? null : Math.round((c / t) * 100);
}

function activeDays(practiceRows: PracticeRow[], mockRows: MockRow[], windowDays = 14): number {
  const cutoff = new Date();
  cutoff.setDate(cutoff.getDate() - windowDays);
  const days = new Set<string>();
  for (const r of practiceRows) {
    const d = new Date(r.created_at);
    if (d >= cutoff) days.add(d.toDateString());
  }
  for (const r of mockRows) {
    const d = new Date(r.created_at);
    if (d >= cutoff) days.add(d.toDateString());
  }
  return days.size;
}

function buildPracticeReportText(rows: PracticeRow[]): string {
  const valid = rows.filter((r) => r.question !== null);
  const total = valid.length;
  const correct = valid.filter((r) => r.is_correct).length;
  const overall = pct(correct, total);

  const lines: string[] = [
    'PRACTICE REPORT',
    '═══════════════',
    `Total attempts : ${total}`,
    `Correct answers: ${correct}`,
    `Overall accuracy: ${overall === null ? 'N/A' : `${overall}%`}`,
    '',
    'ACCURACY BY TOPIC',
    '─────────────────',
  ];

  for (const topic of PRACTICE_TOPICS) {
    const topicRows = valid.filter((r) => r.question?.topic === topic.id);
    const topicCorrect = topicRows.filter((r) => r.is_correct).length;
    const acc = pct(topicCorrect, topicRows.length);
    lines.push(`${topic.label.padEnd(20)} ${acc === null ? 'No data' : `${acc}%`} (${topicRows.length} attempts)`);
  }

  lines.push('');
  lines.push('MOST MISSED TOPICS');
  lines.push('──────────────────');

  const weakTopics = PRACTICE_TOPICS
    .map((t) => {
      const tr = valid.filter((r) => r.question?.topic === t.id);
      const c = tr.filter((r) => r.is_correct).length;
      return { label: t.label, accuracy: pct(c, tr.length) ?? 100, attempts: tr.length };
    })
    .filter((t) => t.attempts >= 3)
    .sort((a, b) => a.accuracy - b.accuracy)
    .slice(0, 3);

  if (weakTopics.length === 0) {
    lines.push('Not enough data yet.');
  } else {
    for (const t of weakTopics) {
      lines.push(`${t.label} — ${t.accuracy}% accuracy`);
    }
  }

  lines.push('');
  lines.push(`Generated by VECTRA on ${new Date().toLocaleDateString()}`);
  return lines.join('\n');
}

function buildMockReportText(rows: MockRow[]): string {
  const count = rows.length;
  const scores = rows.map((r) => pct(r.correct_answers, r.total_questions) ?? 0);
  const avg = count === 0 ? null : Math.round(scores.reduce((a, b) => a + b, 0) / count);
  const best = count === 0 ? null : Math.max(...scores);
  const worst = count === 0 ? null : Math.min(...scores);
  const totalQ = rows.reduce((s, r) => s + r.total_questions, 0);
  const totalSec = rows.reduce((s, r) => s + r.duration_seconds, 0);
  const secsPerQ = totalQ === 0 ? null : Math.round(totalSec / totalQ);

  return [
    'MOCK TEST REPORT',
    '════════════════',
    `Tests taken       : ${count}`,
    `Average score     : ${avg === null ? 'N/A' : `${avg}%`}`,
    `Best score        : ${best === null ? 'N/A' : `${best}%`}`,
    `Worst score       : ${worst === null ? 'N/A' : `${worst}%`}`,
    `Avg time/question : ${secsPerQ === null ? 'N/A' : `${secsPerQ}s`}`,
    '',
    `Generated by VECTRA on ${new Date().toLocaleDateString()}`,
  ].join('\n');
}

function buildReadinessReportText(practiceRows: PracticeRow[], mockRows: MockRow[]): { score: number; text: string } {
  const valid = practiceRows.filter((r) => r.question !== null);
  const total = valid.length;
  const correct = valid.filter((r) => r.is_correct).length;
  const practiceAcc = pct(correct, total) ?? 0;

  const mockScores = mockRows.map((r) => pct(r.correct_answers, r.total_questions) ?? 0);
  const mockAvg = mockScores.length === 0 ? 0 : Math.round(mockScores.reduce((a, b) => a + b, 0) / mockScores.length);

  const consistency = Math.min(100, activeDays(valid, mockRows, 14) * 100 / 14);
  const score = Math.round(practiceAcc * 0.45 + mockAvg * 0.35 + consistency * 0.20);

  const text = [
    'READINESS REPORT',
    '════════════════',
    `Overall readiness score: ${score} / 100`,
    '',
    'BREAKDOWN',
    '─────────',
    `Practice accuracy (45%)  : ${practiceAcc}% → ${Math.round(practiceAcc * 0.45)} pts`,
    `Mock test average (35%)  : ${mockAvg}% → ${Math.round(mockAvg * 0.35)} pts`,
    `Consistency (20%)        : ${Math.round(consistency)}% → ${Math.round(consistency * 0.20)} pts`,
    '',
    'INTERPRETATION',
    '──────────────',
    score >= 80 ? 'Excellent — you are well-prepared for placement tests.'
      : score >= 60 ? 'Good — keep revising your weaker topics.'
        : score >= 40 ? 'Developing — focus on accuracy and consistency.'
          : 'Early stage — complete more practice to improve your score.',
    '',
    `Generated by VECTRA on ${new Date().toLocaleDateString()}`,
  ].join('\n');

  return { score, text };
}

// ─── View State ───────────────────────────────────────────────────────────────

type PageView =
  | { kind: 'loading' }
  | { kind: 'error' }
  | { kind: 'ready'; data: PageData };

// ─── Page ────────────────────────────────────────────────────────────────────

export default function ReportsPage() {
  const [view, setView] = useState<PageView>({ kind: 'loading' });
  const [activeReport, setActiveReport] = useState<ReportType | null>(null);
  const [copied, setCopied] = useState(false);
  const copyTimer = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    document.title = 'Reports | VECTRA';
  }, []);

  useEffect(() => {
    let cancelled = false;

    api<{ practice_rows: Array<{ is_correct: boolean; created_at: string; question: { topic: string; difficulty: string; question: string } | null }>; mock_rows: MockRow[] }>('/analytics/activity')
      .then(({ practice_rows, mock_rows }) => {
        if (cancelled) return;
        const practiceRows: PracticeRow[] = practice_rows.map((r) => ({ ...r, question: r.question ? { ...r.question, topic: normalizeTopic(r.question.topic), difficulty: r.question.difficulty.toLowerCase() as QuestionDifficulty } : null }));
        const mockRows = mock_rows;
        setView({ kind: 'ready', data: { practiceRows, mockRows } });
      })
      .catch(() => { if (!cancelled) setView({ kind: 'error' }); });

    return () => { cancelled = true; };
  }, []);

  function handleGenerate(id: ReportType) {
    setActiveReport((prev) => (prev === id ? null : id));
    setCopied(false);
  }

  function handleCopy(text: string) {
    navigator.clipboard.writeText(text).then(() => {
      setCopied(true);
      if (copyTimer.current) clearTimeout(copyTimer.current);
      copyTimer.current = setTimeout(() => setCopied(false), 2000);
    }).catch(() => { /* clipboard unavailable */ });
  }

  useEffect(() => () => { if (copyTimer.current) clearTimeout(copyTimer.current); }, []);

  return (
    <>
      <PageHeader
        eyebrow="Insights"
        title="Reports"
        description="Generate and export performance summaries for practice, mock tests, and placement readiness."
      />

      {view.kind === 'loading' && (
        <StatePanel variant="loading" title="Loading report data" message="Fetching your performance history." />
      )}
      {view.kind === 'error' && (
        <StatePanel variant="error" title="Reports could not be loaded" message="Check your connection and refresh the page." />
      )}
      {view.kind === 'ready' && (
        <ReportsContent
          data={view.data}
          activeReport={activeReport}
          onGenerate={handleGenerate}
          onCopy={handleCopy}
          copied={copied}
        />
      )}
    </>
  );
}

// ─── Content ─────────────────────────────────────────────────────────────────

interface ReportsContentProps {
  data: PageData;
  activeReport: ReportType | null;
  onGenerate: (id: ReportType) => void;
  onCopy: (text: string) => void;
  copied: boolean;
}

function ReportsContent({ data, activeReport, onGenerate, onCopy, copied }: ReportsContentProps) {
  const { practiceRows, mockRows } = data;

  function getReportText(id: ReportType): string {
    if (id === 'practice') return buildPracticeReportText(practiceRows);
    if (id === 'mock') return buildMockReportText(mockRows);
    return buildReadinessReportText(practiceRows, mockRows).text;
  }

  const readiness = buildReadinessReportText(practiceRows, mockRows);

  return (
    <div className="space-y-6 animate-fade-in">
      {REPORT_CARDS.map((card) => {
        const Icon = card.icon;
        const isOpen = activeReport === card.id;
        const reportText = getReportText(card.id);

        return (
          <article key={card.id} className="rounded-2xl border border-neutral-200/80 bg-white shadow-card overflow-hidden">
            {/* Card header */}
            <div className="flex flex-col gap-4 p-6 sm:flex-row sm:items-start sm:justify-between">
              <div className="flex items-start gap-4">
                <span className={`flex h-10 w-10 flex-shrink-0 items-center justify-center rounded-xl ${card.iconBg}`}>
                  <Icon className={`h-5 w-5 ${card.iconText}`} aria-hidden="true" />
                </span>
                <div>
                  <h2 className="text-base font-semibold text-navy-900">{card.title}</h2>
                  <p className="mt-0.5 text-sm leading-relaxed text-navy-500">{card.summary}</p>

                  {/* Inline readiness score teaser */}
                  {card.id === 'readiness' && (
                    <div className="mt-3 inline-flex items-center gap-2 rounded-xl border border-success-200 bg-success-50/80 px-3 py-1.5">
                      <span className="text-xl font-bold tabular-nums text-success-800">{readiness.score}</span>
                      <span className="text-xs text-success-700">/ 100 readiness score</span>
                    </div>
                  )}
                </div>
              </div>

              <div className="flex flex-shrink-0 items-center gap-2">
                <button
                  type="button"
                  onClick={() => onGenerate(card.id)}
                  className="inline-flex items-center gap-2 rounded-xl bg-primary-600 px-4 py-2.5 text-sm font-semibold text-white shadow-md shadow-primary-600/20 transition-all hover:-translate-y-0.5 hover:bg-primary-700 hover:shadow-lg"
                >
                  {isOpen ? (
                    <>
                      <X className="h-4 w-4" aria-hidden="true" />
                      Close
                    </>
                  ) : (
                    <>
                      <FileText className="h-4 w-4" aria-hidden="true" />
                      Generate
                    </>
                  )}
                </button>
              </div>
            </div>

            {/* Expanded report */}
            {isOpen && (
              <div className="border-t border-neutral-100 px-6 pb-6 pt-5 animate-fade-in">
                <div className="flex items-center justify-between mb-3">
                  <h3 className="text-sm font-semibold text-navy-700">Report content</h3>
                  <button
                    type="button"
                    onClick={() => onCopy(reportText)}
                    className="inline-flex items-center gap-1.5 rounded-xl border border-neutral-200 bg-white px-3 py-1.5 text-xs font-semibold text-navy-700 shadow-card transition-colors hover:bg-neutral-50"
                  >
                    {copied ? (
                      <>
                        <Check className="h-3.5 w-3.5 text-success-600" aria-hidden="true" />
                        Copied!
                      </>
                    ) : (
                      <>
                        <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                        Copy to clipboard
                      </>
                    )}
                  </button>
                </div>

                <pre className="whitespace-pre-wrap rounded-xl bg-neutral-900 p-5 text-xs leading-relaxed text-neutral-100 font-mono overflow-x-auto">
                  {reportText}
                </pre>

                {/* Inline data table for practice report */}
                {card.id === 'practice' && <PracticeReportDetail rows={practiceRows} />}
                {card.id === 'mock' && <MockReportDetail rows={mockRows} />}
                {card.id === 'readiness' && <ReadinessReportDetail score={readiness.score} practiceRows={practiceRows} mockRows={mockRows} />}
              </div>
            )}
          </article>
        );
      })}
    </div>
  );
}

// ─── Report Detail Sections ───────────────────────────────────────────────────

function PracticeReportDetail({ rows }: { rows: PracticeRow[] }) {
  const valid = rows.filter((r) => r.question !== null);
  const topicStats = PRACTICE_TOPICS.map((topic) => {
    const tr = valid.filter((r) => r.question?.topic === topic.id);
    const correct = tr.filter((r) => r.is_correct).length;
    return { label: topic.label, attempts: tr.length, correct, accuracy: pct(correct, tr.length) };
  });

  return (
    <div className="mt-5">
      <h4 className="mb-3 text-sm font-semibold text-navy-800">Topic accuracy table</h4>
      <div className="overflow-x-auto rounded-xl border border-neutral-200">
        <table className="w-full text-sm">
          <thead>
            <tr className="border-b border-neutral-100 text-left text-xs font-semibold uppercase tracking-wider text-navy-400 bg-neutral-50">
              <th className="px-4 py-3">Topic</th>
              <th className="px-4 py-3 text-right">Attempts</th>
              <th className="px-4 py-3 text-right">Correct</th>
              <th className="px-4 py-3 text-right">Accuracy</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-neutral-50">
            {topicStats.map((stat) => (
              <tr key={stat.label} className="hover:bg-neutral-50/50 transition-colors">
                <td className="px-4 py-3 font-medium text-navy-800">{stat.label}</td>
                <td className="px-4 py-3 text-right tabular-nums text-navy-600">{stat.attempts}</td>
                <td className="px-4 py-3 text-right tabular-nums text-navy-600">{stat.correct}</td>
                <td className="px-4 py-3 text-right font-semibold tabular-nums text-navy-900">
                  {stat.accuracy === null ? '—' : `${stat.accuracy}%`}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

function MockReportDetail({ rows }: { rows: MockRow[] }) {
  if (rows.length === 0) {
    return (
      <p className="mt-4 text-sm text-navy-500 italic">No mock test results yet. Take a mock test to see detailed data here.</p>
    );
  }

  const scores = rows.map((r) => pct(r.correct_answers, r.total_questions) ?? 0);
  const totalQ = rows.reduce((s, r) => s + r.total_questions, 0);
  const totalSec = rows.reduce((s, r) => s + r.duration_seconds, 0);

  return (
    <div className="mt-5 grid grid-cols-2 gap-4 sm:grid-cols-4">
      {[
        { label: 'Tests taken', value: String(rows.length) },
        { label: 'Average score', value: `${Math.round(scores.reduce((a, b) => a + b, 0) / scores.length)}%` },
        { label: 'Best score', value: `${Math.max(...scores)}%` },
        { label: 'Avg time / Q', value: totalQ === 0 ? '—' : `${Math.round(totalSec / totalQ)}s` },
      ].map((item) => (
        <div key={item.label} className="rounded-xl border border-neutral-200 bg-neutral-50 p-4 text-center">
          <p className="text-2xl font-bold tabular-nums text-navy-900">{item.value}</p>
          <p className="mt-1 text-xs text-navy-500">{item.label}</p>
        </div>
      ))}
    </div>
  );
}

function ReadinessReportDetail({ score, practiceRows, mockRows }: { score: number; practiceRows: PracticeRow[]; mockRows: MockRow[] }) {
  const valid = practiceRows.filter((r) => r.question !== null);
  const practiceAcc = pct(valid.filter((r) => r.is_correct).length, valid.length) ?? 0;
  const mockScores = mockRows.map((r) => pct(r.correct_answers, r.total_questions) ?? 0);
  const mockAvg = mockScores.length === 0 ? 0 : Math.round(mockScores.reduce((a, b) => a + b, 0) / mockScores.length);
  const consistency = Math.round(Math.min(100, activeDays(valid, mockRows, 14) * 100 / 14));

  const scoreColor = score >= 80 ? 'bg-success-500' : score >= 60 ? 'bg-primary-500' : score >= 40 ? 'bg-warning-500' : 'bg-error-500';

  return (
    <div className="mt-5 space-y-5">
      <div>
        <div className="flex items-center justify-between mb-2">
          <span className="text-sm font-semibold text-navy-800">Overall readiness</span>
          <span className="text-sm font-bold tabular-nums text-navy-900">{score} / 100</span>
        </div>
        <div className="h-3 overflow-hidden rounded-full bg-neutral-100">
          <div className={`h-full rounded-full transition-all duration-700 ease-out ${scoreColor}`} style={{ width: `${score}%` }} />
        </div>
      </div>

      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        {[
          { label: 'Practice accuracy (45%)', value: `${practiceAcc}%`, contribution: Math.round(practiceAcc * 0.45) },
          { label: 'Mock test average (35%)', value: `${mockAvg}%`, contribution: Math.round(mockAvg * 0.35) },
          { label: 'Consistency (20%)', value: `${consistency}%`, contribution: Math.round(consistency * 0.20) },
        ].map((item) => (
          <div key={item.label} className="rounded-xl border border-neutral-200 bg-neutral-50 px-4 py-3">
            <p className="text-xs text-navy-500">{item.label}</p>
            <p className="mt-1 text-lg font-bold tabular-nums text-navy-900">{item.value}</p>
            <p className="text-xs text-primary-600 font-semibold">+{item.contribution} pts</p>
          </div>
        ))}
      </div>
    </div>
  );
}
